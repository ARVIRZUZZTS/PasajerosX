CREATE TABLE IF NOT EXISTS asignacion_boletero (
  id INT AUTO_INCREMENT PRIMARY KEY,
  codR INT NOT NULL,
  boletero_id INT NULL,
  boletero_nombre VARCHAR(150) NULL,
  asignado_por VARCHAR(150) NULL,
  estado VARCHAR(20) NOT NULL DEFAULT 'activo',
  notas TEXT NULL,
  sucursal INT NOT NULL DEFAULT 1,
  sincronizado TINYINT(1) NOT NULL DEFAULT 0,
  deleted TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_asignacion (codR, boletero_id),
  CONSTRAINT fk_asig_reporte FOREIGN KEY (codR) REFERENCES reporte(codR) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS asientos_bloqueados (
  id INT AUTO_INCREMENT PRIMARY KEY,
  codR INT NOT NULL,
  asiento INT NOT NULL,
  motivo VARCHAR(100) NULL,
  zona VARCHAR(50) NULL,
  reservado_para VARCHAR(50) NULL,
  sucursal INT NOT NULL DEFAULT 1,
  sincronizado TINYINT(1) NOT NULL DEFAULT 0,
  deleted TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_bloqueado (codR, asiento),
  CONSTRAINT fk_bloq_reporte FOREIGN KEY (codR) REFERENCES reporte(codR) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS sync_state (
  tabla VARCHAR(50) NOT NULL PRIMARY KEY,
  sucursal INT NOT NULL DEFAULT 1,
  last_sync TIMESTAMP NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
